  void setLanguage(String langCode) {
    if (supportedLanguages.containsKey(langCode) && _currentLanguage != langCode) {
      _currentLanguage = langCode;
      _dbService?.setSetting('app_language', langCode);
      notifyListeners();
    }
  }

